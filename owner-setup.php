$t = $strings[$language];
$keyFile = AIH_STORAGE . '/owner-setup.key';
// Treat a missing, oversized, symlinked or malformed proof as absent.
$readCode = static function () use ($keyFile): string {
    if (!is_file($keyFile) || is_link($keyFile) || !is_readable($keyFile)) return '';
    $size = @filesize($keyFile);
    if ($size === false || $size < 32 || $size > 256) return '';
    $code = trim((string)@file_get_contents($keyFile));
    return preg_match('/\A[A-Za-z0-9_-]{32,128}\z/D', $code) ? $code : '';
};
$available = $readCode() !== '';
$error = '';
$success = false;

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    aih_check_csrf(is_string($_POST['csrf'] ?? null) ? $_POST['csrf'] : null);
    if (!aih_auth_attempt_reserve('owner_setup')) {
        http_response_code(429);
        header('Retry-After: 900');
        $error = $t['rate'];
    } else {
        $providedCode = is_string($_POST['owner_code'] ?? null) ? $_POST['owner_code'] : '';
        $code = $readCode();
        if ($code === '' || strlen($providedCode) > 256 || !hash_equals($code, $providedCode)) {
            http_response_code(403);
            $error = $t['error'];
        } else {
            $pw = is_string($_POST['password'] ?? null) ? $_POST['password'] : '';
            $confirm = is_string($_POST['confirm'] ?? null) ? $_POST['confirm'] : '';
            if (aih_new_password_error($pw) !== '' || !hash_equals($pw, $confirm)) {
                $error = $t['password_error'];
            } else {
                try {
                    $hash = password_hash($pw, PASSWORD_DEFAULT);
                    aih_update_json(AIH_STORAGE . '/settings.json', static function ($current) use ($hash): array {
                        if (!is_array($current) || $current === [] || aih_password_hash_usable((string)($current['password_hash'] ?? ''))) {
                            throw new RuntimeException('Owner setup no longer available.');
                        }
                        $current['password_hash'] = $hash;
                        return aih_migrate_settings($current);
                    });
                    // Password activation succeeded. Existing sessions and remember tokens
                    // are invalidated by the changed password fingerprint, even if a
                    // best-effort cleanup operation cannot write to storage.
                    $success = true;
                    @unlink($keyFile);
                    try {
                        aih_remember_revoke_all();
                        aih_auth_attempt_clear('owner_setup');
                        aih_auth_attempt_clear('login');
                    } catch (Throwable $cleanupError) {
                        error_log('AIH owner setup cleanup failed: ' . get_class($cleanupError));
                    }
                    unset($pw, $confirm, $providedCode, $code);
                } catch (Throwable $e) {
                    error_log('AIH owner setup save failed: ' . get_class($e));
                    $error = $t['storage_error'];
                }
            }
        }
    }
}
